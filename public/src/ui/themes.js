export function normalizeThemeId(id) {
  if (id === 'dark') return 'trace-dark';
  if (id === 'light') return 'trace-light';
  return id || '';
}

export function findThemePreset(id, customThemes = []) {
  const norm = normalizeThemeId(id);
  const custom = Array.isArray(customThemes) ? customThemes.find(t => t && t.id === norm) : null;
  if (custom) return custom;
  return THEME_PRESETS.find(t => t.id === norm) || null;
}

export function getAllThemes(customThemes = []) {
  const validCustom = Array.isArray(customThemes)
    ? customThemes.filter(t => t && t.id && t.name && t.tokens).map(t => ({ ...t, isCustom: true, category: 'Custom' }))
    : [];
  return [...THEME_PRESETS, ...validCustom];
}

export function resolveThemeSpec(themeId, customThemes = [], settings = DEFAULT_SETTINGS) {
  const base = findThemePreset(themeId, customThemes) || THEME_PRESETS[0];
  const mergedTokens = { ...THEME_PRESETS[base.scheme === 'light' ? 1 : 0].tokens, ...base.tokens };
  if (!mergedTokens['--btn-dark-bg']) mergedTokens['--btn-dark-bg'] = base.scheme === 'dark' ? mergedTokens['--accent'] : '#2c3228';
  if (!mergedTokens['--btn-dark-fg']) mergedTokens['--btn-dark-fg'] = base.scheme === 'dark' ? mergedTokens['--accent-fg'] : '#ffffff';
  if (!mergedTokens['--accent-border']) mergedTokens['--accent-border'] = mergedTokens['--green'];
  if (!mergedTokens['--brand-fg']) mergedTokens['--brand-fg'] = mergedTokens['--accent'];
  if (!mergedTokens['--hover']) mergedTokens['--hover'] = mergedTokens['--active'];

  const waveMode = settings?.waveCanvasMode || 'always-dark';
  const effectiveTokens = { ...mergedTokens };
  if (waveMode === 'always-dark') {
    Object.assign(effectiveTokens, DARK_WAVE_OVERRIDE);
    effectiveTokens['--wave-cursor'] = base.scheme === 'dark' ? (mergedTokens['--green'] || DARK_WAVE_OVERRIDE['--wave-cursor']) : DARK_WAVE_OVERRIDE['--wave-cursor'];
  }

  const termMode = settings?.termThemeMode || 'always-dark';
  if (termMode === 'always-dark' && base.scheme !== 'dark') {
    Object.assign(effectiveTokens, DARK_TERM_OVERRIDE);
  }

  return {
    id: base.id,
    name: base.name,
    scheme: base.scheme === 'light' ? 'light' : 'dark',
    isCustom: !!base.isCustom,
    baseTokens: mergedTokens,
    tokens: effectiveTokens,
  };
}

export function normalizeCssHex(val, fallback = '#000000') {
  const s = String(val || '').trim();
  if (/^#[0-9a-fA-F]{6}$/.test(s)) return s.toLowerCase();
  if (/^#[0-9a-fA-F]{3}$/.test(s)) return ('#' + s[1] + s[1] + s[2] + s[2] + s[3] + s[3]).toLowerCase();
  if (/^#[0-9a-fA-F]{8}$/.test(s)) return s.slice(0, 7).toLowerCase();
  return fallback;
}

export function hexWithAlpha(hex, alphaHex) {
  return `${normalizeCssHex(hex)}${alphaHex}`;
}

export function applyThemeToDocument(spec, settings = DEFAULT_SETTINGS) {
  const root = document.documentElement;
  root.dataset.theme = spec.id;
  root.dataset.scheme = spec.scheme;

  const style = root.style;
  for (const [k, v] of Object.entries(spec.tokens)) {
    style.setProperty(k, v);
  }
  const fontSize = Math.max(10, Math.min(20, Number(settings?.editorFontSize) || 12));
  const lineHeight = Math.round(fontSize * 1.65);
  const tabSize = Math.max(1, Math.min(8, Number(settings?.editorTabSize) || 2));
  style.setProperty('--ce-font', settings?.editorFontFamily || DEFAULT_SETTINGS.editorFontFamily);
  style.setProperty('--ce-font-size', `${fontSize}px`);
  style.setProperty('--ce-line-height', `${lineHeight}px`);
  style.setProperty('--ce-tab-size', String(tabSize));

  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.content = spec.tokens['--bg'];

  try {
    localStorage.setItem('trace.theme', spec.id);
    localStorage.setItem(THEME_CACHE_KEY, JSON.stringify({
      id: spec.id,
      scheme: spec.scheme,
      tokens: spec.tokens,
      editorFontSize: fontSize,
      editorLineHeight: lineHeight,
      editorTabSize: tabSize,
      editorFontFamily: settings?.editorFontFamily || DEFAULT_SETTINGS.editorFontFamily,
    }));
  } catch {}
}

export function loadStoredSettings() {
  try {
    const raw = localStorage.getItem(SETTINGS_KEY);
    if (!raw) return { ...DEFAULT_SETTINGS };
    const parsed = JSON.parse(raw);
    return { ...DEFAULT_SETTINGS, ...(parsed && typeof parsed === 'object' ? parsed : {}) };
  } catch {
    return { ...DEFAULT_SETTINGS };
  }
}

export function saveStoredSettings(settings) {
  try {
    localStorage.setItem(SETTINGS_KEY, JSON.stringify(settings));
  } catch {}
}

export function loadStoredCustomThemes() {
  try {
    const raw = localStorage.getItem(CUSTOM_THEMES_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.filter(t => t && t.id && t.name && t.tokens) : [];
  } catch {
    return [];
  }
}

export function saveStoredCustomThemes(list) {
  try {
    localStorage.setItem(CUSTOM_THEMES_KEY, JSON.stringify(Array.isArray(list) ? list : []));
  } catch {}
}
